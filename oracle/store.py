"""Prediction log.

`live.jsonl`     append-only. One frozen forecast per race, made before the race. Each record
                 carries the hash of the previous one, so any later edit breaks the chain.
                 The file is committed to git, which adds an independent timestamp.
`backtest.jsonl` forecasts regenerated by walk-forward replay of past races; clearly not live.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

GENESIS = "0" * 64


def _canonical(record: dict) -> str:
    return json.dumps(record, sort_keys=True, separators=(",", ":"))


def record_hash(record: dict, prev: str) -> str:
    body = {k: v for k, v in record.items() if k not in ("hash", "prev")}
    return hashlib.sha256((prev + _canonical(body)).encode()).hexdigest()


def read_log(path: Path) -> list[dict]:
    path = Path(path)
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def verify_chain(records: list[dict]) -> tuple[bool, str]:
    prev = GENESIS
    for i, rec in enumerate(records):
        if rec.get("prev") != prev:
            return False, f"record {i} does not follow the previous record"
        if rec.get("hash") != record_hash(rec, prev):
            return False, f"record {i} ({rec.get('season')} R{rec.get('round')}) was modified"
        prev = rec["hash"]
    return True, f"{len(records)} records, chain intact"


def append_live(path: Path, record: dict) -> bool:
    """Append a forecast. Returns False (and writes nothing) if that race is already logged."""
    path = Path(path)
    records = read_log(path)
    ok, msg = verify_chain(records)
    if not ok:
        raise RuntimeError(f"refusing to append to a broken log: {msg}")
    if any((r["season"], r["round"]) == (record["season"], record["round"]) for r in records):
        return False
    prev = records[-1]["hash"] if records else GENESIS
    record = {**record, "prev": prev}
    record["hash"] = record_hash(record, prev)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "a") as f:
        f.write(_canonical(record) + "\n")
    return True


def write_backtest(path: Path, records: list[dict]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(_canonical(r) + "\n" for r in records))
